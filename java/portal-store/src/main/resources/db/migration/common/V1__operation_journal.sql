-- Concurrency limits as primary keys (design 13.2). scope is 'GLOBAL' or 'TARGET:<targetId>'; slot_no counts from 1. A claim inserts the smallest free
-- slot_no of each scope in the same transaction that moves the operation to STARTING; two claims for the same slot_no collide on the primary key.
-- A slot is deleted in the transaction that moves the operation out of STARTING / RUNNING / TERMINATING (also when it moves to UNKNOWN).
-- An operation owns two rows (global and target), so operation_id alone is not unique.
CREATE TABLE operation_slot (
    scope        VARCHAR(40) NOT NULL,
    slot_no      INTEGER     NOT NULL,
    operation_id CHAR(48)    NOT NULL,
    CONSTRAINT pk_operation_slot PRIMARY KEY (scope, slot_no),
    CONSTRAINT uq_operation_slot_operation UNIQUE (scope, operation_id),
    CONSTRAINT fk_operation_slot_op FOREIGN KEY (operation_id) REFERENCES operation (id),
    CONSTRAINT ck_operation_slot_no CHECK (slot_no >= 1)
);

-- conflictKey fence: one live operation per (target, revision, conflict key). The conflict key is stored as its SHA-256 (hex) so that the key stays short
-- enough for a primary key on MariaDB and MySQL (an InnoDB index key is limited to 3072 bytes). A row is deleted when the operation reaches one of the five final
-- states and is kept while it is UNKNOWN, so that an operation of uncertain outcome keeps blocking its conflict key.
CREATE TABLE operation_fence (
    target_id       VARCHAR(32) NOT NULL,
    target_revision CHAR(64)    NOT NULL,
    conflict_digest CHAR(64)    NOT NULL,
    operation_id    CHAR(48)    NOT NULL,
    CONSTRAINT pk_operation_fence PRIMARY KEY (target_id, target_revision, conflict_digest),
    CONSTRAINT fk_operation_fence_op FOREIGN KEY (operation_id) REFERENCES operation (id)
);
