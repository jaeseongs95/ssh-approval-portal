-- Operation journal (2.x operations, operation_events, operation_legacy_budget and the body fields of the command journal), design 8.2 and 13.2.
-- Common to every DBMS: ANSI types only (CHAR, VARCHAR, INTEGER, BIGINT, DOUBLE PRECISION, TIMESTAMP(6)), no IDENTITY, no CLOB, no function, no trigger.
-- The long-text columns (CLOB in H2, TEXT in PostgreSQL, MEDIUMTEXT in MariaDB and MySQL) have no common type; they are added by the vendor script
-- db/migration/{vendor}/V1_1__long_text_columns.sql, which Flyway picks with the {vendor} placeholder of spring.flyway.locations
-- (https://docs.spring.io/spring-boot/how-to/data-initialization.html, "Execute Flyway Database Migrations on Startup").
-- The identifiers are made by the application (48 hex characters); no column is generated by the database.
--
-- The list of values of an enum column is checked with CASE WHEN col = 'A' THEN 1 ... END = 1 and not with col IN ('A', 'B'): H2 2.4.240 turns an IN list of two or more
-- constants (and an OR chain of equalities, which it rewrites to one) into a set that keeps the session that created the constraint, so the first insert after the
-- migration connection is closed fails with "Check constraint invalid ... The database has been closed" (reproduced with an embedded H2 2.4.240 database: a check
-- with IN, an OR chain or a NULL-or-IN fails, a check with <>, CHAR_LENGTH or AND/OR of comparisons of different columns works). CASE is ANSI and means the same in
-- PostgreSQL, MariaDB and MySQL.

CREATE TABLE operation (
    id                        CHAR(48)      NOT NULL,
    request_key               VARCHAR(512)  NOT NULL,
    owner_id                  VARCHAR(512)  NOT NULL,
    target_id                 VARCHAR(512)  NOT NULL,
    target_revision           VARCHAR(64)   NOT NULL,
    kind                      VARCHAR(9)    NOT NULL,
    state                     VARCHAR(11)   NOT NULL,
    version                   BIGINT        NOT NULL,
    approval_mode             VARCHAR(11)   NOT NULL,
    profile                   VARCHAR(80)   NOT NULL,
    input_digest              CHAR(64),
    contract_digest           CHAR(64)      NOT NULL,
    conflict_key              VARCHAR(512),
    ready_sequence            BIGINT,
    created_at                TIMESTAMP(6)  NOT NULL,
    updated_at                TIMESTAMP(6)  NOT NULL,
    expires_at                TIMESTAMP(6),
    ready_at                  TIMESTAMP(6),
    started_at                TIMESTAMP(6),
    finished_at               TIMESTAMP(6),
    cancellation_requested_at TIMESTAMP(6),
    outcome_certainty         VARCHAR(14),
    reconciliation            VARCHAR(12),
    recovery_reason           VARCHAR(14)   NOT NULL,
    audit_failure             VARCHAR(6)    NOT NULL,
    CONSTRAINT pk_operation PRIMARY KEY (id),
    CONSTRAINT uq_operation_request_key UNIQUE (request_key),
    CONSTRAINT uq_operation_ready_sequence UNIQUE (ready_sequence),
    CONSTRAINT ck_operation_kind CHECK (CASE WHEN kind = 'COMMAND' THEN 1 WHEN kind = 'SOURCE' THEN 1 WHEN kind = 'UPLOAD' THEN 1 WHEN kind = 'DOWNLOAD' THEN 1 WHEN kind = 'AGENT_CLI' THEN 1 ELSE 0 END = 1),
    CONSTRAINT ck_operation_state CHECK (CASE WHEN state = 'ACCEPTED' THEN 1 WHEN state = 'PENDING' THEN 1 WHEN state = 'EVALUATING' THEN 1 WHEN state = 'QUEUED' THEN 1 WHEN state = 'STARTING' THEN 1 WHEN state = 'RUNNING' THEN 1 WHEN state = 'TERMINATING' THEN 1 WHEN state = 'COMPLETED' THEN 1 WHEN state = 'FAILED' THEN 1 WHEN state = 'CANCELLED' THEN 1 WHEN state = 'DENIED' THEN 1 WHEN state = 'EXPIRED' THEN 1 WHEN state = 'UNKNOWN' THEN 1 ELSE 0 END = 1),
    CONSTRAINT ck_operation_approval CHECK (CASE WHEN approval_mode = 'OWNER' THEN 1 WHEN approval_mode = 'AUTOMATIC' THEN 1 WHEN approval_mode = 'NOT_DECIDED' THEN 1 ELSE 0 END = 1),
    CONSTRAINT ck_operation_certainty CHECK (CASE WHEN outcome_certainty IS NULL THEN 1 WHEN outcome_certainty = 'NOT_DISPATCHED' THEN 1 WHEN outcome_certainty = 'EXITED' THEN 1 WHEN outcome_certainty = 'UNKNOWN' THEN 1 ELSE 0 END = 1),
    CONSTRAINT ck_operation_reconcile CHECK (CASE WHEN reconciliation IS NULL THEN 1 WHEN reconciliation = 'NOT_REQUIRED' THEN 1 WHEN reconciliation = 'REQUIRED' THEN 1 ELSE 0 END = 1),
    CONSTRAINT ck_operation_recovery CHECK (CASE WHEN recovery_reason = 'NONE' THEN 1 WHEN recovery_reason = 'BRIDGE_RESTART' THEN 1 WHEN recovery_reason = 'LEGACY_IMPORT' THEN 1 ELSE 0 END = 1),
    CONSTRAINT ck_operation_audit CHECK (CASE WHEN audit_failure = 'NONE' THEN 1 WHEN audit_failure = 'FAILED' THEN 1 ELSE 0 END = 1),
    CONSTRAINT ck_operation_revision CHECK (CHAR_LENGTH(target_revision) = 64 OR target_revision = 'legacy-unbound'),
    CONSTRAINT ck_operation_version CHECK (version >= 1),
    -- The digest of the intent is the whole input of an agent CLI operation (AgentCliInput); the other kinds have their own input table.
    CONSTRAINT ck_operation_input_digest CHECK ((kind = 'AGENT_CLI' AND input_digest IS NOT NULL) OR (kind <> 'AGENT_CLI' AND input_digest IS NULL))
);
CREATE INDEX ix_operation_ready ON operation (state, ready_sequence);
CREATE INDEX ix_operation_target_state ON operation (target_id, state);
CREATE INDEX ix_operation_created ON operation (created_at, id);

-- One row per transition. The pair (operation_id, version) is the key: every transition raises the version by one, so no generated sequence is needed.
CREATE TABLE operation_event (
    operation_id   CHAR(48)     NOT NULL,
    version        BIGINT       NOT NULL,
    state          VARCHAR(11)  NOT NULL,
    occurred_at    TIMESTAMP(6) NOT NULL,
    CONSTRAINT pk_operation_event PRIMARY KEY (operation_id, version),
    CONSTRAINT fk_operation_event_op FOREIGN KEY (operation_id) REFERENCES operation (id),
    CONSTRAINT ck_operation_event_state CHECK (CASE WHEN state = 'ACCEPTED' THEN 1 WHEN state = 'PENDING' THEN 1 WHEN state = 'EVALUATING' THEN 1 WHEN state = 'QUEUED' THEN 1 WHEN state = 'STARTING' THEN 1 WHEN state = 'RUNNING' THEN 1 WHEN state = 'TERMINATING' THEN 1 WHEN state = 'COMPLETED' THEN 1 WHEN state = 'FAILED' THEN 1 WHEN state = 'CANCELLED' THEN 1 WHEN state = 'DENIED' THEN 1 WHEN state = 'EXPIRED' THEN 1 WHEN state = 'UNKNOWN' THEN 1 ELSE 0 END = 1)
);

